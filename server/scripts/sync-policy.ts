import { readFileSync, writeFileSync } from "node:fs";

// Copies docs/privacy-policy.md into lib/record/policy-text.ts, because `vercel deploy` uploads only server/ and a function cannot
// read a file outside its bundle. test/record.test.ts fails if the two differ.   npm run sync-policy
const here = new URL(".", import.meta.url).pathname;
const text = readFileSync(`${here}../../docs/privacy-policy.md`, "utf8");
const header = "// GENERATED by scripts/sync-policy.ts from docs/privacy-policy.md. Do not edit by hand; run `npm run sync-policy`.\n";
writeFileSync(`${here}../lib/record/policy-text.ts`, `${header}export const PRIVACY_POLICY_MD = ${JSON.stringify(text)};\n`);
console.log(`policy-text.ts written (${text.length} characters)`);
